#!/usr/bin/env python3
"""Cluster E, Prover 1 (least-residue route): exact computations.

All arithmetic exact (Python integers / fractions.Fraction).
Definitions (TARGET.md):
  H(a,b)=A/B in lowest terms, B=den H(a,b)
  L(a,b)=lcm(a..b)
  For odd prime p, p^2>b, k(p)>=1 multiples in [a,b],
    T_p = sum_{j} 1/(u+j) in F_p over multiples p*(u+j)
  P1 = {p : T_p != 0}, Q = prod_{p in P1} p^2 (1 if empty)
  forced class: m = -p*(T_p)^{-1} (mod p^2) for p in P1, CRT -> r mod Q
  r0 = least positive representative (1 if Q=1).
Smoothness of r0 is tested by trial division by all primes <= b:
after removing them, remainder 1 iff b-smooth; remainder >1 iff a
prime factor > b exists (so NOT b-smooth). This is a decision, not
a full factorisation of the remainder.
"""
from fractions import Fraction
from math import isqrt, gcd, log
import sys

def primes_upto(n):
    if n < 2: return []
    s = bytearray(b"\x01")*(n+1); s[0]=s[1]=0
    for i in range(2, isqrt(n)+1):
        if s[i]:
            s[i*i::i] = b"\x00"*len(s[i*i::i])
    return [i for i,v in enumerate(s) if v]

def factorize(n, primes):
    out={}
    for p in primes:
        if p*p>n: break
        while n%p==0:
            out[p]=out.get(p,0)+1; n//=p
    if n>1: out[n]=out.get(n,0)+1
    return out

def interval_data(a,b,primes_all):
    """Exact (B, L, Q, r0, P1 list). Requires primes_all up to b."""
    L=1
    for n in range(a,b+1):
        L = L*n//gcd(L,n)
    N=sum(L//n for n in range(a,b+1))
    g=gcd(N,L); B=L//g
    # candidate good/bad primes: odd prime divisors > sqrt(b) of some n in [a,b]
    cand=set()
    sb=isqrt(b)
    small=primes_upto(isqrt(b)+1)
    for n in range(a,b+1):
        for p in factorize(n, small):
            if p!=2 and p>sb:
                cand.add(p)
    congr=[]; P1=[]
    for p in sorted(cand):
        # multiples
        first = -(-a//p)*p
        tot=0; mults=[]
        m=first
        while m<=b:
            mults.append(m); tot=(tot+pow(m//p,-1,p))%p; m+=p
        if mults and tot!=0:
            P1.append(p); congr.append(((-p*pow(tot,-1,p))%(p*p), p*p))
    r=0; M=1
    for rp,mod in congr:
        r = r + M*(((rp-r)*pow(M%mod,-1,mod))%mod); M*=mod; r%=M
    Q=M; r0 = r if Q>1 else 1
    if Q>1 and r0==0: r0=Q  # least positive representative if residue 0
    return B,L,Q,r0,P1

def is_b_smooth(n,b,primes_all):
    if n==1: return True
    m=n
    for p in primes_all:
        if p>b: break
        while m%p==0: m//=p
        if m==1: return True
    return m==1

def report(a,b,primes_all,label=""):
    B,L,Q,r0,P1=interval_data(a,b,primes_all)
    sm=is_b_smooth(r0,b,primes_all) if Q>1 else True
    inclass = (B%Q==r0%Q) if Q>1 else True
    print(f"{label} (a,b)=({a},{b}) R={b-a+1} B={B} L={L} Q={Q} r0={r0} "
          f"|P1|={len(P1)} P1={P1[:8]}{'...' if len(P1)>8 else ''} "
          f"r0<=L:{r0<=L} r0_b_smooth:{sm} B_in_forced_class:{inclass}")
    return B,L,Q,r0,P1

def main():
    print("=== Section 1: R=1 family a=b=p(p-1), p prime ===")
    print("Claim: P1={p}, Q=p^2, r0=p, L=a=p(p-1), r0<=L and r0 b-smooth.")
    P=primes_upto(100000)
    for p in [3,5,7,11,13,101,1009,10007]:
        a=p*(p-1)
        report(a,a,P,f"p={p}")
    print()
    print("=== Section 2: R=2 Pell family t^2-2s^2=-1, interval (t^2,t^2+1) ===")
    print("Claim: t^2+1=2 s^2, P1 empty, Q=1, r0=1 (sieve-blind degeneracy).")
    # Pell solutions generated by (t+s*sqrt2) = (1+sqrt2)^(odd powers)
    t,s=1,1
    sols=[]
    for _ in range(6):
        sols.append((t,s))
        t,s = t+2*s, t+s  # multiply by (3+2 sqrt2)? check below with recurrence on (t,s)->(3t+4s, 2t+3s) instead
    # regenerate cleanly via fundamental unit powers
    sols=[]; t,s=1,1
    for _ in range(5):
        assert t*t-2*s*s==-1, (t,s)
        sols.append((t,s))
        t,s = 3*t+4*s, 2*t+3*s
    for (t,s) in sols:
        a=t*t; b=a+1
        report(a,b,P,f"t={t},s={s},t^2+1=2s^2={2*s*s}")
    print()
    print("=== Section 3: R=2 intervals (a,a+1), scan a<=200000 for B in forced class with P1 nonempty ===")
    print("Characterisation used for scan (proved in prover1.md): for R=2,")
    print("B=a(a+1) lies in forced class iff no good prime divides a.")
    # Direct exact interval_data on the found examples only; scan via factor condition.
    N=200000
    spf=[0]*(N+2)
    pr=primes_upto(N+1)
    for p in pr:
        for j in range(p, N+2, p):
            if spf[j]==0: spf[j]=p
    def prime_factors_distinct(n):
        out=set()
        while n>1:
            p=spf[n] if n<=N+1 and spf[n] else n
            out.add(p); 
            while n%p==0: n//=p
        return out
    found=[]
    for a in range(3, N+1):
        b=a+1
        ok=True
        for p in prime_factors_distinct(a):
            if p!=2 and p*p>b: ok=False; break
        if not ok: continue
        # P1 nonempty iff b has an odd prime factor p with p^2>b
        if any(p!=2 and p*p>b for p in prime_factors_distinct(b)):
            found.append(a)
    print(f"count a<={N} with B in class and P1 nonempty: {len(found)}")
    print(f"first 40: {found[:40]}")
    print(f"examples near top: {found[-10:]}")
    # verify a sample exactly with interval_data (b small enough for exact L,B,Q)
    Psamp=primes_upto(3000)
    for a in found[:12]:
        if a<=2000: report(a,a+1,Psamp,"scan-verify")
    print()
    print("=== Section 4: fixed R scan, R=1..6, a up to 300: least-residue successes/failures ===")
    P300=primes_upto(300)
    for R in range(1,7):
        cnt_le_smooth=0; cnt_r0_gt=0; cnt_r0_nonsmooth=0; total=0; first_fail=None
        for a in range(2, 300-R+2):
            b=a+R-1
            B,L,Q,r0,P1=interval_data(a,b,P300)
            if Q==1: continue
            total+=1
            if r0>L: cnt_r0_gt+=1
            elif is_b_smooth(r0,b,P300): 
                cnt_le_smooth+=1
                if first_fail is None: first_fail=(a,b,r0,L)
            else: cnt_r0_nonsmooth+=1
        print(f"R={R}: intervals Q>1: {total}, r0>L: {cnt_r0_gt}, r0<=L & nonsmooth: {cnt_r0_nonsmooth}, "
              f"r0<=L & b-smooth (least-residue FAILS): {cnt_le_smooth}, first_fail={first_fail}")
    print()
    print("=== Section 5: regime (ii) a>b/2, selected samples ===")
    for (a,b) in [(50,60),(55,80),(60,100),(90,150),(120,200),(180,300),(240,400),(300,500)]:
        Pb=primes_upto(b)
        report(a,b,Pb,"regime-ii")
    print()
    print("=== Section 6: regime (ii) strip b/2<a, 3a<=2b+1: scan b<=200 ===")
    P200=primes_upto(200)
    tot=0; r0gt=0; r0le_sm=0; r0le_ns=0
    for b in range(10,201):
        for a in range(b//2+1, b+1):
            if 3*a>2*b+1: continue
            B,L,Q,r0,P1=interval_data(a,b,P200)
            if Q==1: continue
            tot+=1
            if r0>L: r0gt+=1
            elif is_b_smooth(r0,b,P200): r0le_sm+=1
            else: r0le_ns+=1
    print(f"strip intervals (Q>1) b<=200: {tot}, r0>L: {r0gt}, r0<=L nonsmooth: {r0le_ns}, r0<=L smooth: {r0le_sm}")
    print()
    print("=== Section 7: the strip prime ell in (b/4,b/2) for large b (modular only) ===")
    print("For each b: ell = a prime in (b/4,b/2) (Bertrand), J = {j in {2,3}: j*ell in [a,b]},")
    print("S = sum_{j in J} 1/j (exact fraction), T_ell = S mod ell. Expect J nonempty, T != 0.")
    def bertrand_prime(n):
        # prime in (n, 2n)
        ps=primes_upto(2*n)
        for p in ps:
            if p>n: return p
        return None
    bad=0; tested=0
    for b in [100,999,10000,100000,1000000]:
        for frac_num,frac_den in [(11,20),(3,5),(13,20)]:
            a=b*frac_num//frac_den + 1
            if not (2*a>b and 3*a<=2*b+1): 
                print(f"  b={b} a={a}: not in strip, skipped"); continue
            ell=bertrand_prime(b//4)
            assert b/4 < ell < b/2, (b,ell)
            J=[j for j in (2,3) if a<=j*ell<=b]
            S=sum((Fraction(1,j) for j in J), Fraction(0))
            T = (S.numerator * pow(S.denominator,-1,ell))%ell if J else None
            tested+=1
            if not J or T==0: bad+=1
            print(f"  b={b} a={a} ell={ell} J={J} S={S} T_ell_mod_ell={T} ell^2>b:{ell*ell>b}")
    print(f"tested {tested}, bad {bad}")
    print()
    print("=== Section 8: regime (ii), subregime A samples (3a>=2b+2): H<1/2 check ===")
    for (a,b) in [(100,140),(1000,1499),(10000,14999)]:
        H=sum((Fraction(1,n) for n in range(a,b+1)), Fraction(0)) if b-a<2000 else None
        R=b-a+1
        print(f"  (a,b)=({a},{b}) R={R} R/a={R}/{a}={R/a:.4f} (<=0.5 required: {2*R<=a})"
              + (f" H={float(H):.6f} <0.5: {H<Fraction(1,2)}" if H is not None else " H not summed (interval long); bound H<R/a applies"))

if __name__=="__main__":
    main()
